#!/usr/bin/env node
// ぐるぐる星わたり：ボット（galaxy/bot.js）が本物のエンジンでクリアした入力の記録を galaxy/proofs.js に書く。
//   node tools/galaxy-proofs.js
'use strict';
const fs = require('fs'), path = require('path');
const E = require('../galaxy/engine.js'), LV = require('../galaxy/levels.js'), Bot = require('../galaxy/bot.js');
const out = {}; let bad = 0;
for (const g of LV.GALAXIES) { const L = LV.compile(E, g.id); for (const m of L.mlist) { const r = Bot.run(L, m.id); if (!r.ok) { console.log('FAIL', m.id, r.fail); bad++; continue; } out[m.id] = { f: r.frames, h: E.hash(r.S), rec: E.rle(r.rec) }; console.log('ok', m.id, r.frames); } }
let s = '// generated by tools/galaxy-proofs.js : the bot\'s input recording (run-length, base 36) that clears each mission on the real engine; replayed by the unit tests\n(function (root) {\n  var P = {\n';
s += Object.keys(out).map(k => ' ' + JSON.stringify(k) + ': ' + JSON.stringify(out[k])).join(',\n');
s += '\n  };\n  if (typeof module !== \'undefined\' && module.exports) module.exports = P; else root.GalaxyProofs = P;\n})(typeof window !== \'undefined\' ? window : globalThis);\n';
fs.writeFileSync(path.join(__dirname, '../galaxy/proofs.js'), s); process.exit(bad ? 1 : 0);
