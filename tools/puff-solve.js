#!/usr/bin/env node
// ふわふわぱふ solver: the route bot (puff/bot.js) plays every stage on the real engine; the winning input recording (which also picks up all
// three medals) is stored in puff/proofs.js and replayed by tools/tests/unit/puff-levels.test.js.
//   node tools/puff-solve.js 1-1 [2-3 ...]   solve some stages and print the result
//   node tools/puff-solve.js --all [--write] solve every stage (--write: store puff/proofs.js)
//   node tools/puff-solve.js --show 1-2      print the ASCII map
'use strict';
const fs = require('fs'), path = require('path');
const E = require('../puff/engine.js'), LV = require('../puff/levels.js'), PB = require('../puff/bot.js');

function solve(id, o) {
  o = o || {}; const def = LV.get(id), L = E.parse(def);
  const S = E.newState(L, o.state || {}), bot = PB.create(def), inputs = [];
  const max = o.max || 36000;
  while (!S.res && inputs.length < max && !bot.fail) { const m = bot.step(S); inputs.push(m); E.step(S, m); }
  return { id, ok: !!S.res, frames: inputs.length, inputs, S, fail: bot.fail, bi: bot.i, deaths: S.deaths, hurts: S.hurts, med: S.med };
}
function popc(n) { let c = 0; while (n) { c += n & 1; n >>>= 1; } return c; }
if (require.main === module) {
  const a = process.argv.slice(2);
  if (a[0] === '--show') { const d = LV.get(a[1]); d.rows.forEach((r, i) => console.log(String(i).padStart(2) + ' ' + r)); console.log(JSON.stringify(d.route.slice(0, 60))); process.exit(0); }
  const ids = a.includes('--all') ? LV.ids() : a.filter(x => /^\d+-\d+$/.test(x));
  const out = {}; let bad = 0;
  for (const id of ids) {
    const t0 = Date.now(), r = solve(id), m = popc(r.med);
    const good = r.ok && m === 3;
    console.log(id, good ? 'OK ' : 'FAIL', 'frames', r.frames, 'medals', m, 'hurts', r.hurts, 'deaths', r.deaths, 'route', r.bi + '/' + LV.get(id).route.length, r.fail || '', (Date.now() - t0) + 'ms');
    if (!good) bad++; else out[id] = E.rle(r.inputs);
  }
  if (a.includes('--write') && !bad) {
    const body = Object.keys(out).map(k => ' ' + JSON.stringify(k) + ': ' + JSON.stringify(out[k])).join(',\n');
    fs.writeFileSync(path.join(__dirname, '../puff/proofs.js'), '// generated by tools/puff-solve.js : an input recording (run-length, base 36) that finishes each stage with all three medals; replayed by the unit tests\n(function (root) {\n  var P = {\n' + body + '\n  };\n  if (typeof module === \'object\' && module && module.exports) module.exports = P;\n  root.PuffProofs = P;\n})(typeof window !== \'undefined\' ? window : globalThis);\n');
    console.log('wrote puff/proofs.js');
  }
  process.exit(bad ? 1 : 0);
}
module.exports = { solve };
